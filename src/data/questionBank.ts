// ---------------------------------------------------------------------------
// Pool builder: picks a weighted, shuffled set of questions per category so
// the "question numbers" board feels full, and difficulty biases the mix.
// ---------------------------------------------------------------------------

const WEIGHTS: Record<Difficulty, Record<Difficulty, number>> = {
  easy: { easy: 5, medium: 2, hard: 1, legendary: 0.4 },
  medium: { easy: 2.5, medium: 4, hard: 2, legendary: 1 },
  hard: { easy: 1, medium: 2, hard: 4, legendary: 2.5 },
  legendary: { easy: 0.4, medium: 1, hard: 3.5, legendary: 5 },
};

const POOL_SIZE = 12;

export function poolFor(category: CategoryId, difficulty: Difficulty): Question[] {
  const source = BANK[category];
  if (source.length <= POOL_SIZE) return [...source];
  const weights = WEIGHTS[difficulty];
  const remaining = [...source];
  const picked: Question[] = [];
  let total = remaining.reduce((s, q) => s + weights[q.difficulty], 0);
  while (picked.length < POOL_SIZE && remaining.length > 0) {
    let r = Math.random() * total;
    let idx = 0;
    for (let i = 0; i < remaining.length; i++) {
      r -= weights[remaining[i].difficulty];
      if (r <= 0) {
        idx = i;
        break;
      }
      idx = i;
    }
    const [q] = remaining.splice(idx, 1);
    picked.push(q);
    total = remaining.reduce((s, qq) => s + weights[qq.difficulty], 0);
  }
  return picked;
}

/** All questions flattened (for the daily challenge). */
export const ALL_QUESTIONS: Question[] = Object.values(BANK).flat();

export function dailyQuestion(dateStr: string): Question {
  let h = 0;
  for (let i = 0; i < dateStr.length; i++) h = (h * 31 + dateStr.charCodeAt(i)) >>> 0;
  return ALL_QUESTIONS[h % ALL_QUESTIONS.length];
}
